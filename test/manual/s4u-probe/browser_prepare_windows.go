const browserPreparationInput = `C:\smoke\browser-preparation-input.json`
const browserPreparationResult = `C:\smoke\browser-preparation-result.json`

type browserPreparation struct {
	Fixture browserfixture.Fixture
	Error   string
}
type browserPreparationService struct{ input string }

func (this *browserPreparationService) Execute(_ []string, controls <-chan svc.ChangeRequest, statuses chan<- svc.Status) (bool, uint32) {
	statuses <- svc.Status{State: svc.StartPending}
	fixture, err := readSystemPreparationInput(this.input)
	if err == nil {
		fixture, err = initializeSystemBrowserState(fixture)
	}
	result := browserPreparation{Fixture: fixture}
	if err != nil {
		result.Error = err.Error()
	}
	raw, encodeErr := json.Marshal(result)
	if encodeErr != nil || writeBrowserPreparationResult(raw) != nil {
		return false, 1
	}
	if err != nil {
		return false, 1
	}
	statuses <- svc.Status{State: svc.Running, Accepts: svc.AcceptStop}
	timer := time.NewTimer(30 * time.Second)
	defer timer.Stop()
	for {
		select {
		case request := <-controls:
			if request.Cmd == svc.Stop {
				statuses <- svc.Status{State: svc.StopPending}
				return false, 0
			}
			if request.Cmd == svc.Interrogate {
				statuses <- request.CurrentStatus
			}
		case <-timer.C:
			return false, 1
		}
	}
}

func readSystemPreparationInput(path string) (browserfixture.Fixture, error) {
	var fixture browserfixture.Fixture
	sid, err := currentSID()
	if err != nil || sid != "S-1-5-18" {
		return fixture, fmt.Errorf("private browser fixture state must be generated by container LocalSystem")
	}
	marker, err := os.ReadFile(`C:\smoke\servercore-container.marker`)
	if err != nil || strings.TrimSpace(string(marker)) != "bifroest-servercore-integration" {
		return fixture, fmt.Errorf("not the owned Server Core preparation image")
	}
	if path != browserPreparationInput {
		return fixture, fmt.Errorf("unexpected preparation input")
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		return fixture, err
	}
	if err := json.Unmarshal(raw, &fixture); err != nil {
		return fixture, err
	}
	if !strings.HasPrefix(fixture.Service, "bifroest-browser-") {
		return fixture, fmt.Errorf("not an owned fixture service")
	}
	nonce := strings.TrimPrefix(fixture.Service, "bifroest-browser-")
	if decoded, err := hex.DecodeString(nonce); err != nil || len(decoded) != 16 || strings.ToLower(nonce) != nonce {
		return fixture, fmt.Errorf("invalid fixture service nonce")
	}
	if fixture.Root != filepath.Join(os.Getenv("ProgramData"), fixture.Service) || fixture.Probe != filepath.Join(fixture.Root+"-bin", "probe.exe") {
		return fixture, fmt.Errorf("preparation paths escaped owned fixture")
	}
	host, err := os.Hostname()
	if err != nil {
		return fixture, err
	}
	account, domain, kind, err := windows.LookupSID("", host+`\`+fixture.User)
	if err != nil || account == nil || kind != windows.SidTypeUser || !strings.EqualFold(domain, host) || account.String() != fixture.SID {
		return fixture, fmt.Errorf("preparation account identity changed")
	}
	return fixture, nil
}

// Only public fixture pins/error text are returned to the controller. This ACL
// is not used for any private key: those retain the native protected writer.
func writeBrowserPreparationResult(raw []byte) error {
	sd, err := windows.SecurityDescriptorFromString("D:P(A;;FA;;;SY)(A;;FA;;;BA)")
	if err != nil {
		return err
	}
	sa := &windows.SecurityAttributes{Length: uint32(unsafe.Sizeof(windows.SecurityAttributes{})), SecurityDescriptor: sd}
	temporary := browserPreparationResult + ".pending"
	path, err := windows.UTF16PtrFromString(temporary)
	if err != nil {
		return err
	}
	handle, err := windows.CreateFile(path, windows.GENERIC_WRITE, 0, sa, windows.CREATE_NEW, windows.FILE_ATTRIBUTE_NORMAL, 0)
	if err != nil {
		return err
	}
	file := os.NewFile(uintptr(handle), temporary)
	defer os.Remove(temporary)
	_, writeErr := file.Write(raw)
	if err := errors.Join(writeErr, file.Sync(), file.Close()); err != nil {
		return err
	}
	return os.Rename(temporary, browserPreparationResult)
}

func prepareBrowserStateAsSystem(fixture browserfixture.Fixture) (_ browserfixture.Fixture, resultErr error) {
	if err := requireBrowserContainer(); err != nil {
		return fixture, err
	}
	raw, err := json.Marshal(fixture)
	if err != nil {
		return fixture, err
	}
	if err := writeBrowserPrivateFile(browserPreparationInput, raw); err != nil {
		return fixture, err
	}
	manager, err := mgr.Connect()
	if err != nil {
		return fixture, err
	}
	defer func() { resultErr = errors.Join(resultErr, manager.Disconnect()) }()
	service, err := manager.CreateService(fixture.Service+"-prepare", fixture.Probe, mgr.Config{StartType: mgr.StartManual, ServiceStartName: "LocalSystem"}, "browser-prepare", fixture.Service+"-prepare", browserPreparationInput)
	if err != nil {
		return fixture, err
	}
	defer service.Close()
	defer func() { _, _ = service.Control(svc.Stop); _ = service.Delete() }()
	startErr := service.Start()
	deadline := time.Now().Add(5 * time.Second)
	var readErr error
	for {
		raw, readErr = os.ReadFile(browserPreparationResult)
		if readErr == nil || startErr != nil || !os.IsNotExist(readErr) || time.Now().After(deadline) {
			break
		}
		status, err := service.Query()
		if err != nil {
			return fixture, err
		}
		if status.State == svc.Stopped {
			return fixture, fmt.Errorf("system preparation stopped before publishing its result: %d", status.Win32ExitCode)
		}
		time.Sleep(20 * time.Millisecond)
	}
	if readErr != nil {
		return fixture, fmt.Errorf("system fixture preparation: %w", errors.Join(startErr, readErr))
	}
	var prepared browserPreparation
	if err := json.Unmarshal(raw, &prepared); err != nil {
		return fixture, err
	}
	if prepared.Error != "" {
		return fixture, fmt.Errorf("system fixture preparation failed: %s", prepared.Error)
	}
	if startErr != nil {
		return fixture, startErr
	}
	if prepared.Fixture.Service != fixture.Service || prepared.Fixture.Root != fixture.Root || prepared.Fixture.User != fixture.User || prepared.Fixture.SID != fixture.SID || prepared.Fixture.Probe != fixture.Probe {
		return fixture, fmt.Errorf("system preparation returned a different fixture identity")
	}
	if _, err := service.Control(svc.Stop); err != nil {
		return fixture, err
	}
	deadline = time.Now().Add(5 * time.Second)
	for time.Now().Before(deadline) {
		status, err := service.Query()
		if err != nil {
			return fixture, err
		}
		if status.State == svc.Stopped {
			if status.Win32ExitCode != 0 {
				return fixture, fmt.Errorf("system preparation stopped with %d", status.Win32ExitCode)
			}
			return prepared.Fixture, nil
		}
		time.Sleep(20 * time.Millisecond)
	}
	return fixture, fmt.Errorf("system fixture preparation did not stop")
}
